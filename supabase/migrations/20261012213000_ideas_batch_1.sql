-- Перша пачка ідей: задачі Claude окремо від плану, «Застряг», автофільтр, чекліст партії,
-- листи постачальнику, календар. Позначки товарів, підказки до задач і листи засіяні окремо через SQL.
alter table public.tasks drop constraint tasks_source_check;
alter table public.tasks add constraint tasks_source_check check (source in ('manual','plan','analyst','claude'));
alter table public.tasks
  add column if not exists help text,
  add column if not exists stuck_note text,
  add column if not exists stuck_at timestamptz;
update public.tasks set source = 'claude' where id in (select task_id from public.ideas where task_id is not null);

alter table public.products
  add column if not exists fit_block text[] not null default '{}',
  add column if not exists fit_warn text[] not null default '{}',
  add column if not exists batch_check text[] not null default '{}';

alter table public.templates drop constraint templates_kind_check;
alter table public.templates add constraint templates_kind_check check (kind in ('chat','listing','ad','insert','supplier'));

create table if not exists public.calendar_events (
  id uuid primary key default gen_random_uuid(),
  kind text not null check (kind in ('season','tax','china','market')),
  title text not null,
  note text,
  starts_on date not null,
  ends_on date,
  created_at timestamptz not null default now()
);
create index if not exists calendar_events_starts_idx on public.calendar_events(starts_on);
alter table public.calendar_events enable row level security;
create policy "members all" on public.calendar_events for all to authenticated
  using ((select public.is_member())) with check ((select public.is_member()));

