-- Чорний список: шахраї й ті, кого вписали вручну. Невикупи з замовлень рахуються самі.
create table if not exists public.blacklist (
  phone text primary key,
  reason text,
  created_at timestamptz not null default now()
);
alter table public.blacklist enable row level security;
create policy "members all" on public.blacklist for all to authenticated
  using ((select public.is_member())) with check ((select public.is_member()));

-- Банк реальних питань покупців.
create table if not exists public.customer_questions (
  id uuid primary key default gen_random_uuid(),
  question text not null,
  answer text,
  product_id uuid references public.products(id) on delete set null,
  times int not null default 1,
  in_listing boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create trigger customer_questions_touch before update on public.customer_questions
  for each row execute function public.touch_updated_at();
alter table public.customer_questions enable row level security;
create policy "members all" on public.customer_questions for all to authenticated
  using ((select public.is_member())) with check ((select public.is_member()));

-- Коли посилка прибула у відділення: від цієї дати рахуємо, скільки вона лежить.
alter table public.orders add column if not exists arrived_at timestamptz;

